import pickle

#______________________________________________________________________________
#
# region print_divider
#______________________________________________________________________________
def print_divider(title):
    print('\n{} {} {}\n'.format('-' * 25, title, '-' * 25))
#______________________________________________________________________________
#
# region load_pickle
#______________________________________________________________________________
def load_pickle(fp):
    with open(fp, 'rb') as f:
        return pickle.load(f)
